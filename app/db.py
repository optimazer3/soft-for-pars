_pool: ConnectionPool | None = None
_pool_lock = threading.Lock()


class DatabaseNotConfigured(RuntimeError):
    pass


def database_url() -> str:
    url = os.environ.get("DATABASE_URL", "").strip()
    if not url:
        raise DatabaseNotConfigured(
            "Не задан DATABASE_URL. Скопируйте .env.example в .env и вставьте строку подключения Supabase."
        )
    if "supabase" in url and "sslmode=" not in url:
        url += ("&" if "?" in url else "?") + "sslmode=require"
    return url


def check_connection() -> None:
    """Connect once and fail fast with a clear (Russian) message."""
    url = database_url()
    if "[YOUR-PASSWORD]" in url or "xxxxxxxx" in url:
        raise DatabaseNotConfigured("В .env осталась строка-пример: вставьте свою строку подключения и пароль базы.")
    try:
        psycopg.connect(url, connect_timeout=15).close()
    except psycopg.OperationalError as exc:
        text = str(exc)
        if "password authentication failed" in text:
            hint = "неверный пароль базы данных (его можно сбросить в Supabase: Database → Settings)"
        elif "Tenant or user not found" in text:
            hint = "неверное имя пользователя — в строке должно быть postgres.<id проекта>"
        elif "translate host name" in text or "getaddrinfo" in text or "Name or service not known" in text:
            hint = "адрес сервера не найден — проверьте строку подключения и интернет"
        elif "timeout" in text.lower():
            hint = "сервер не отвечает — проверьте интернет"
        else:
            hint = text.strip().splitlines()[-1]
        raise DatabaseNotConfigured(f"Не удалось подключиться к базе: {hint}") from None


def pool() -> ConnectionPool:
    global _pool
    with _pool_lock:
        if _pool is None:
            p = ConnectionPool(
                database_url(), min_size=1, max_size=4, open=False, timeout=20,
                # prepare_threshold=None: works with Supabase's transaction pooler too
                kwargs={"row_factory": dict_row, "prepare_threshold": None, "autocommit": True},
            )
            p.open(wait=True, timeout=30)
            _pool = p
    return _pool


def init() -> None:
    """Connect and create/upgrade the schema."""
    with pool().connection() as c:
        for sql in MIGRATIONS:
            c.execute(sql)
    migrate_client_passwords()


def migrate_client_passwords() -> None:
    """Convert passwords encrypted by older versions to plain text (needs data/secret.key)."""
    has_enc = query_one(
        "SELECT 1 AS x FROM information_schema.columns "
        "WHERE table_schema = %s AND table_name = 'clients' AND column_name = 'password_enc'",
        (SCHEMA_NAME,),
    )
    if not has_enc:
        return
    from .crypto import decrypt  # only needed for this one-time conversion

    rows = query(f"SELECT id, password_enc FROM {SCHEMA_NAME}.clients "
                 "WHERE password IS NULL AND password_enc IS NOT NULL")
    failed = 0
    for r in rows:
        try:
            plain = decrypt(r["password_enc"])
        except Exception:  # noqa: BLE001 - wrong/missing key
            failed += 1
            continue
        execute(f"UPDATE {SCHEMA_NAME}.clients SET password = %s, password_enc = NULL WHERE id = %s",
                (plain, r["id"]))
    if failed:
        print(f"  Не удалось расшифровать пароли у {failed} клиент(ов): нет нужного data/secret.key. "
              "Укажите пароль заново при редактировании клиента.")
        return
    execute(f"ALTER TABLE {SCHEMA_NAME}.clients DROP COLUMN password_enc")


def close() -> None:
    global _pool
    with _pool_lock:
        if _pool is not None:
            _pool.close()
            _pool = None


def now() -> datetime:
    return datetime.now().astimezone()


def now_iso() -> str:
    return now().isoformat(timespec="seconds")


def _run(fn):
    """Run fn(connection). A connection that died while idle (sleep, network change) is
    replaced by the pool, so one retry is enough to hide the hiccup from the user."""
    try:
        with pool().connection() as c:
            return fn(c)
    except psycopg.OperationalError:
        with pool().connection() as c:
            return fn(c)


def query(sql: str, params: tuple | dict | None = None) -> list[dict]:
    return _run(lambda c: c.execute(sql, params).fetchall())


def query_one(sql: str, params: tuple | dict | None = None) -> dict | None:
    return _run(lambda c: c.execute(sql, params).fetchone())


def execute(sql: str, params: tuple | dict | None = None) -> int:
    """Run a write statement; returns the affected row count."""
    return _run(lambda c: c.execute(sql, params).rowcount)


# ---------- settings (cached: they are read on every request) ----------

_settings_cache: tuple[float, dict] | None = None
SETTINGS_TTL = 5.0


def get_settings() -> dict[str, Any]:
    global _settings_cache
    if _settings_cache and time.monotonic() - _settings_cache[0] < SETTINGS_TTL:
        return dict(_settings_cache[1])
    stored = {r["key"]: r["value"] for r in query("SELECT key, value FROM app.settings")}
    merged = {**DEFAULT_SETTINGS, **stored}
    _settings_cache = (time.monotonic(), merged)
    return dict(merged)


def set_settings(values: dict[str, Any]) -> dict[str, Any]:
    global _settings_cache
    with pool().connection() as c, c.transaction():
        for k, v in values.items():
            c.execute(
                "INSERT INTO app.settings(key, value) VALUES(%s, %s) "
                "ON CONFLICT(key) DO UPDATE SET value = excluded.value",
                (k, Jsonb(v)),
            )
    _settings_cache = None
    return get_settings()


def delete_settings(keys: list[str]) -> None:
    global _settings_cache
    execute("DELETE FROM app.settings WHERE key = ANY(%s)", (keys,))
    _settings_cache = None


# ---------- snapshots ----------

def save_snapshot(client_id: int, period: str, source_updated_at: str | None,
                  kpi: dict, branches: list[dict], progress: dict | None = None,
                  extras: dict | None = None) -> None:
    ts = now()
    execute(
        """
        INSERT INTO app.snapshots(client_id, day, period, fetched_at, source_updated_at, kpi, branches, progress, extras)
        VALUES(%s, %s, %s, %s, %s, %s, %s, %s, %s)
        ON CONFLICT(client_id, day) DO UPDATE SET
            period = excluded.period,
            fetched_at = excluded.fetched_at,
            source_updated_at = excluded.source_updated_at,
            kpi = excluded.kpi,
            branches = excluded.branches,
            progress = excluded.progress,
            extras = excluded.extras
        """,
        (client_id, ts.date(), period, ts, source_updated_at, Jsonb(kpi), Jsonb(branches),
         Jsonb(progress) if progress is not None else None, Jsonb(extras or {})),
    )


def latest_snapshot(client_id: int) -> dict | None:
    return query_one(
        "SELECT client_id, day, period, fetched_at, source_updated_at, kpi, branches, progress, extras "
        "FROM app.snapshots WHERE client_id = %s ORDER BY fetched_at DESC LIMIT 1",
        (client_id,),
    )


def prune_logs(days: int = 90) -> None:
    """The sign-in log and finished sessions are kept for 90 days."""
    execute("DELETE FROM app.events WHERE at < now() - make_interval(days => %s)", (days,))
    execute("DELETE FROM app.sessions WHERE last_seen_at < now() - make_interval(days => %s)", (days,))


def prune_snapshots(retention_days: int) -> int:
    """Delete snapshots older than N days, always keeping each client's newest one."""
    return execute(
        """
        DELETE FROM app.snapshots s
        WHERE s.day < current_date - %s::int
          AND EXISTS (SELECT 1 FROM app.snapshots n
                      WHERE n.client_id = s.client_id AND n.fetched_at > s.fetched_at)
        """,
        (max(1, int(retention_days)),),
    )
